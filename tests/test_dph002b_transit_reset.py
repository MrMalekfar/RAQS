def _physical_rho(rng):
    """Random physical density matrix (PSD, trace 1)."""
    A = rng.normal(size=(4, 4)) + 1j * rng.normal(size=(4, 4))
    rho = A @ A.conj().T
    return qt.Qobj(rho / np.trace(rho))


def _dissipator(c_ops, rho):
    out = qt.Qobj(np.zeros((4, 4), dtype=complex))
    for c in c_ops:
        out = out + c * rho * c.dag() - 0.5 * (c.dag() * c * rho + rho * c.dag() * c)
    return out


# ---------------------------------------------------------------------------
# TEST 1 — reset-channel Liouvillian identity
# ---------------------------------------------------------------------------
def test_reset_liouvillian_identity():
    rng = np.random.default_rng(42)
    gamma = 0.855
    c_ops = create_transit_reset_collapse_ops(gamma)
    assert len(c_ops) == 4
    s1 = qt.basis(4, 0)
    for _ in range(5):
        rho = _physical_rho(rng)
        lhs = _dissipator(c_ops, rho)
        rhs = gamma * (s1.proj() * rho.tr() - rho)
        assert np.allclose(lhs.full(), rhs.full(), atol=1e-12)


# ---------------------------------------------------------------------------
# TEST 2 — trace preservation
# ---------------------------------------------------------------------------
def test_reset_channel_preserves_trace():
    rng = np.random.default_rng(7)
    c_ops = create_transit_reset_collapse_ops(1.37)
    for _ in range(4):
        rho = _physical_rho(rng)
        assert abs(np.trace(_dissipator(c_ops, rho).full())) < 1e-12


# ---------------------------------------------------------------------------
# TEST 3 — population relaxation (loss with ground replenishment)
# ---------------------------------------------------------------------------
def test_reset_population_relaxation():
    gamma = 0.9
    c_ops = create_transit_reset_collapse_ops(gamma)
    s1 = qt.basis(4, 0)
    for j in range(1, 4):
        rho = qt.basis(4, j).proj()
        d = _dissipator(c_ops, rho)
        assert d.full()[j, j] == pytest.approx(-gamma, abs=1e-12)      # loss
        assert d.full()[0, 0] == pytest.approx(+gamma, abs=1e-12)      # replenish
    d = _dissipator(c_ops, s1.proj())                                  # |1> stationary
    assert np.allclose(d.full(), 0.0, atol=1e-12)


# ---------------------------------------------------------------------------
# TEST 4 — coherence relaxation at the FULL rate Gamma_t
# ---------------------------------------------------------------------------
def test_reset_coherence_relaxation():
    gamma = 1.1
    c_ops = create_transit_reset_collapse_ops(gamma)
    for (a, b) in [(0, 1), (0, 2), (2, 3)]:   # rho_12, rho_13, rho_34
        M = np.zeros((4, 4), dtype=complex)
        M[a, b] = 1.0
        d = _dissipator(c_ops, qt.Qobj(M))
        assert d.full()[a, b] == pytest.approx(-gamma * 1.0, abs=1e-12)


# ---------------------------------------------------------------------------
# TEST 5 — independent rate oracle (effective Markovian transit rate)
# ---------------------------------------------------------------------------
def test_transit_rate_independent_oracle():
    # DPH-002C: use the PRODUCTION temperature owner (parameters), not the
    # duplicated constants value.
    T = params.VAPOR_CELL_TEMPERATURE_K
    m = acfg.ATOM.mass
    w0 = LASER_PARAMS['probe']['beam_waist_mm'] * 1e-3
    # first-principles oracle with the project's documented constant k_B
    expected = np.sqrt(2 / np.pi) * np.sqrt(const.k_B * T / m) / w0 * 1e-6
    got = calculate_transit_rate_per_us()
    assert got == pytest.approx(expected, rel=1e-12)
    # cross-check against the CODATA value (project k_B is rounded to 3 s.f.)
    assert got == pytest.approx(
        np.sqrt(2 / np.pi) * np.sqrt(sc.k * T / m) / w0 * 1e-6, rel=1e-3)
    v_rms_over_w = np.sqrt(const.k_B * T / m) / w0 * 1e-6     # plain v/w0 (DPH-002A)
    assert got == pytest.approx(np.sqrt(2 / np.pi) * v_rms_over_w, rel=1e-9)
    assert got != pytest.approx(2 * np.pi * expected, rel=0.5)  # no 2pi revival


# ---------------------------------------------------------------------------
# TEST 6 — no transit double-counting
# ---------------------------------------------------------------------------
def test_no_transit_double_counting(atomic_physics):
    T = const.VAPOR_CELL_TEMPERATURE_K
    m = acfg.ATOM.mass
    n = params.CALCULATED_N0
    n_ryd = acfg.ATOMIC_LEVELS['rydberg1']['n']
    sigma = 1e-14 * (n_ryd / 50.0) ** 4 * 1e-4                # independent collision oracle
    v_rel = np.sqrt(8 * const.k_B * T / (np.pi * m))
    coll = n * sigma * v_rel * 1e-6
    dep = calculate_dephasing_rates()
    assert dep[2] == pytest.approx(params.GAMMA_RF_LINEWIDTH + coll, rel=1e-9)
    assert dep[0] == pytest.approx(params.GAMMA_PROBE_LINEWIDTH + coll, rel=1e-9)
    gamma_t = calculate_transit_rate_per_us()
    for d in dep:                                             # transit absent from budget
        assert d != pytest.approx(d + gamma_t, rel=1e-6)
    H, c_ops, obs = create_sensor_model(                      # 3+3+4 = 10 collapse ops
        7.86, 56.66, 21.01, 0.0, 0.0, 0.0,
        [acfg.GAMMA_21, acfg.GAMMA_32, acfg.GAMMA_43],
        dep, transit_rate_per_us=gamma_t,
    )
    assert len(c_ops) == 10
    for r in create_transit_reset_collapse_ops(gamma_t):
        assert any(np.allclose(c.full(), r.full()) for c in c_ops)


